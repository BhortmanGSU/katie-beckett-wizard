const systemFields: FieldSpec[] = BODY_SYSTEMS.flatMap((s): FieldSpec[] => {
  const y = SYSTEM_Y[s.id];
  return [
    {
      kind: 'check',
      label: `${s.label} — None`,
      page: 0,
      x: 155,
      y: y + 3,
      size: 8,
      section: 'doctor',
      when: ({ profile }) => !profile.health.systems[s.id]?.has,
    },
    {
      kind: 'text',
      label: `${s.label} — Description`,
      page: 0,
      x: 218,
      y: y + 1,
      size: 8.5,
      maxWidth: 350,
      section: 'doctor',
      value: ({ profile }) => (profile.health.systems[s.id]?.has ? profile.health.systems[s.id].description : ''),
    },
  ];
});

